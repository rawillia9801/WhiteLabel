create table if not exists heat_cycles (
  id bigint generated by default as identity primary key,
  kennel_id uuid not null references kennels(id) on delete cascade,
  dog_id bigint not null references dogs(id) on delete cascade,
  start_date date not null,
  end_date date,
  predicted_next_heat date,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_date is null or end_date >= start_date)
);

create table if not exists progesterone_tests (
  id bigint generated by default as identity primary key,
  kennel_id uuid not null references kennels(id) on delete cascade,
  dog_id bigint not null references dogs(id) on delete cascade,
  heat_cycle_id bigint references heat_cycles(id) on delete set null,
  tested_at timestamptz not null,
  result numeric(10,3) not null,
  units text not null default 'ng/mL',
  laboratory text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (result >= 0)
);

create table if not exists breeding_attempts (
  id bigint generated by default as identity primary key,
  kennel_id uuid not null references kennels(id) on delete cascade,
  litter_id bigint references litters(id) on delete cascade,
  dam_id bigint not null references dogs(id) on delete restrict,
  sire_id bigint not null references dogs(id) on delete restrict,
  heat_cycle_id bigint references heat_cycles(id) on delete set null,
  attempted_at timestamptz not null,
  method text not null default 'Natural',
  status text not null default 'Recorded',
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (dam_id <> sire_id)
);

create table if not exists genetic_tests (
  id bigint generated by default as identity primary key,
  kennel_id uuid not null references kennels(id) on delete cascade,
  dog_id bigint not null references dogs(id) on delete cascade,
  condition text not null,
  gene text,
  result_status text not null check (result_status in ('Clear', 'Carrier', 'Affected', 'At Risk', 'Indeterminate', 'Not Tested')),
  inheritance_mode text not null default 'Autosomal Recessive',
  provider text,
  result_date date,
  laboratory_reference text,
  dog_document_id bigint references dog_documents(id) on delete set null,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists puppy_weight_logs (
  id bigint generated by default as identity primary key,
  kennel_id uuid not null references kennels(id) on delete cascade,
  puppy_id bigint not null references puppies(id) on delete cascade,
  measured_at timestamptz not null default now(),
  weight numeric(12,4) not null check (weight > 0),
  unit text not null default 'oz' check (unit in ('oz', 'lb', 'g', 'kg')),
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists puppy_care_records (
  id bigint generated by default as identity primary key,
  kennel_id uuid not null references kennels(id) on delete cascade,
  puppy_id bigint not null references puppies(id) on delete cascade,
  care_type text not null,
  title text not null,
  care_date date not null,
  product text,
  lot_number text,
  provider text,
  next_due_date date,
  notes text,
  visible_in_portal boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists waitlist_entries (
  id bigint generated by default as identity primary key,
  kennel_id uuid not null references kennels(id) on delete cascade,
  buyer_id bigint not null references buyers(id) on delete cascade,
  litter_id bigint references litters(id) on delete set null,
  preferred_sex text,
  preferred_color text,
  preferred_coat_type text,
  other_preferences text,
  deposit_status text not null default 'Not received',
  priority_rank integer not null default 0,
  picking_position integer,
  status text not null default 'Waiting' check (status in ('Waiting', 'Ready to Pick', 'Puppy Assigned', 'Passed', 'Next Litter', 'On Hold', 'Completed', 'Removed')),
  assigned_puppy_id bigint references puppies(id) on delete set null,
  retain_priority boolean not null default true,
  joined_at timestamptz not null default now(),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (picking_position is null or picking_position > 0)
);

create table if not exists waitlist_history (
  id bigint generated by default as identity primary key,
  kennel_id uuid not null references kennels(id) on delete cascade,
  waitlist_entry_id bigint not null references waitlist_entries(id) on delete cascade,
  action text not null,
  from_position integer,
  to_position integer,
  from_status text,
  to_status text,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
