-- Direct Supabase access is tenant-isolated too. Server-side service-role requests
-- continue to work because service-role bypasses RLS, while authenticated clients
-- can only operate on kennels where they are an explicit member.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'dogs', 'dog_medical_records', 'dog_registrations', 'dog_documents',
    'buyers', 'litters', 'puppies', 'payment_plans', 'payment_plan_puppies',
    'transactions', 'buyer_documents', 'buyer_document_puppies', 'events', 'puppy_updates',
    'heat_cycles', 'progesterone_tests', 'breeding_attempts', 'genetic_tests',
    'puppy_weight_logs', 'puppy_care_records', 'waitlist_entries', 'waitlist_history'
  ]
  loop
    execute format('alter table %I enable row level security', table_name);
    execute format('drop policy if exists "kennel members manage rows" on %I', table_name);
    execute format(
      'create policy "kennel members manage rows" on %I for all to authenticated using (exists (select 1 from kennel_members km where km.kennel_id = %I.kennel_id and km.auth_user_id = auth.uid())) with check (exists (select 1 from kennel_members km where km.kennel_id = %I.kennel_id and km.auth_user_id = auth.uid()))',
      table_name, table_name, table_name
    );
  end loop;
end $$;

-- Atomic waitlist assignment keeps the buyer, puppy, and audit record in sync.
create or replace function assign_waitlist_puppy(
  p_kennel_id uuid,
  p_entry_id bigint,
  p_puppy_id bigint,
  p_actor uuid default null
) returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  entry_record waitlist_entries%rowtype;
  puppy_record puppies%rowtype;
begin
  select * into entry_record from waitlist_entries where id = p_entry_id and kennel_id = p_kennel_id for update;
  if not found then raise exception 'Waitlist entry was not found in this kennel.'; end if;

  select * into puppy_record from puppies where id = p_puppy_id and kennel_id = p_kennel_id for update;
  if not found then raise exception 'Puppy was not found in this kennel.'; end if;
  if puppy_record.buyer_id is not null and puppy_record.buyer_id <> entry_record.buyer_id then
    raise exception 'This puppy is already assigned to another family.';
  end if;

  update puppies
  set buyer_id = entry_record.buyer_id, status = 'Reserved', updated_at = now()::text
  where id = p_puppy_id and kennel_id = p_kennel_id;

  update buyers
  set application_status = 'Matched', updated_at = now()::text
  where id = entry_record.buyer_id and kennel_id = p_kennel_id;

  update waitlist_entries
  set status = 'Puppy Assigned', assigned_puppy_id = p_puppy_id, updated_at = now()
  where id = p_entry_id and kennel_id = p_kennel_id;

  insert into waitlist_history (
    kennel_id, waitlist_entry_id, action, from_position, to_position,
    from_status, to_status, notes, created_by
  ) values (
    p_kennel_id, p_entry_id, 'Puppy assigned', entry_record.picking_position,
    entry_record.picking_position, entry_record.status, 'Puppy Assigned',
    'Puppy #' || p_puppy_id || ' assigned to buyer #' || entry_record.buyer_id, p_actor
  );
end;
$$;

create or replace function move_waitlist_entry(
  p_kennel_id uuid,
  p_entry_id bigint,
  p_direction integer,
  p_actor uuid default null
) returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_entry waitlist_entries%rowtype;
  swap_entry waitlist_entries%rowtype;
  target_position integer;
begin
  if p_direction not in (-1, 1) then raise exception 'Direction must be -1 or 1.'; end if;
  select * into current_entry from waitlist_entries where id = p_entry_id and kennel_id = p_kennel_id for update;
  if not found then raise exception 'Waitlist entry was not found in this kennel.'; end if;
  if current_entry.picking_position is null then raise exception 'This waitlist entry has no picking position.'; end if;

  select * into swap_entry
  from waitlist_entries
  where kennel_id = p_kennel_id
    and id <> p_entry_id
    and status not in ('Completed', 'Removed')
    and ((p_direction = -1 and picking_position < current_entry.picking_position)
      or (p_direction = 1 and picking_position > current_entry.picking_position))
  order by case when p_direction = -1 then picking_position end desc,
           case when p_direction = 1 then picking_position end asc
  limit 1
  for update;

  if not found then return; end if;
  target_position := swap_entry.picking_position;
  update waitlist_entries set picking_position = current_entry.picking_position, updated_at = now() where id = swap_entry.id and kennel_id = p_kennel_id;
  update waitlist_entries set picking_position = target_position, updated_at = now() where id = current_entry.id and kennel_id = p_kennel_id;
  insert into waitlist_history (kennel_id, waitlist_entry_id, action, from_position, to_position, from_status, to_status, created_by)
  values (p_kennel_id, current_entry.id, 'Picking order changed', current_entry.picking_position, target_position, current_entry.status, current_entry.status, p_actor);
end;
$$;

create or replace function sync_breeding_calendar(
  p_kennel_id uuid,
  p_litter_id bigint,
  p_breeding_date date
) returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from litters where id = p_litter_id and kennel_id = p_kennel_id) then
    raise exception 'Litter was not found in this kennel.';
  end if;

  delete from events
  where kennel_id = p_kennel_id and related_type = 'litter' and related_id = p_litter_id
    and notes like '[AUTO:BREEDING]%';

  if p_breeding_date is null then return; end if;

  insert into events (kennel_id, title, event_type, event_date, related_type, related_id, status, notes, created_at, updated_at)
  values
    (p_kennel_id, 'Ultrasound window opens', 'Pregnancy', (p_breeding_date + 25)::text, 'litter', p_litter_id, 'Scheduled', '[AUTO:BREEDING] +25 days', now()::text, now()::text),
    (p_kennel_id, 'Mid-pregnancy check-in', 'Pregnancy', (p_breeding_date + 30)::text, 'litter', p_litter_id, 'Scheduled', '[AUTO:BREEDING] +30 days', now()::text, now()::text),
    (p_kennel_id, 'Prepare whelping supplies', 'Whelping prep', (p_breeding_date + 45)::text, 'litter', p_litter_id, 'Scheduled', '[AUTO:BREEDING] +45 days', now()::text, now()::text),
    (p_kennel_id, 'X-ray / puppy-count window', 'Pregnancy', (p_breeding_date + 55)::text, 'litter', p_litter_id, 'Scheduled', '[AUTO:BREEDING] +55 days', now()::text, now()::text),
    (p_kennel_id, 'Expected whelping window begins', 'Whelping', (p_breeding_date + 58)::text, 'litter', p_litter_id, 'Scheduled', '[AUTO:BREEDING] +58 days', now()::text, now()::text),
    (p_kennel_id, 'Estimated due date', 'Whelping', (p_breeding_date + 63)::text, 'litter', p_litter_id, 'Scheduled', '[AUTO:BREEDING] +63 days', now()::text, now()::text),
    (p_kennel_id, 'Expected whelping window ends', 'Whelping', (p_breeding_date + 65)::text, 'litter', p_litter_id, 'Scheduled', '[AUTO:BREEDING] +65 days', now()::text, now()::text);
end;
$$;

